from datetime import datetime, timedelta
from decimal import Decimal
import random

from dotenv import load_dotenv
from faker import Faker
from sqlalchemy import select

from models import config, enums
from models.transactions import Transactions
from models.savings_goals import SavingsGoals
from models.debts import Debts
from models.crypto_holding import CryptoHolding

load_dotenv()

fake = Faker()
Faker.seed(42)
random.seed(42)


def check_transactions_exist():
    stmt = select(Transactions.id).limit(1)
    result = config.session.execute(stmt).scalar_one_or_none()
    return result is not None


def check_savings_goal_exists(name: str):
    stmt = select(SavingsGoals).where(SavingsGoals.name == name)
    return config.session.execute(stmt).scalars().first() is not None


def check_debt_exists(name: str):
    stmt = select(Debts).where(Debts.name == name)
    return config.session.execute(stmt).scalars().first() is not None


def check_crypto_exists(symbol: str):
    stmt = select(CryptoHolding).where(CryptoHolding.symbol == symbol)
    return config.session.execute(stmt).scalars().first() is not None


def seed_savings_goals():
    if check_savings_goal_exists("House Down Payment") or check_savings_goal_exists("Emergency Fund"):
        print("Savings goals already exist, skipping...")
        return

    goals = [
        SavingsGoals(
            name="House Down Payment",
            target_amount=Decimal("50000.00"),
            current_amount=Decimal("20000.00"),
            deadline=datetime(2028, 6, 1),
            monthly_contribution=Decimal("800.00"),
            status=enums.SavingsGoalsStatusEnum.active,
        ),
        SavingsGoals(
            name="Emergency Fund",
            target_amount=Decimal("10000.00"),
            current_amount=Decimal("3000.00"),
            deadline=datetime(2027, 1, 1),
            monthly_contribution=Decimal("200.00"),
            status=enums.SavingsGoalsStatusEnum.active,
        ),
    ]

    for goal in goals:
        goal.add_SavingsGoals(config.session)
        print(f"Added savings goal: {goal.name}")


