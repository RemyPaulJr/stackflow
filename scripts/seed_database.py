def seed_transactions():
    if check_transactions_exist():
        print("Transactions already exist, skipping...")
        return

    today = datetime.now()
    start_date = today - timedelta(days=180)

    transactions = []

    current_date = start_date
    while current_date <= today:
        if current_date.weekday() == 4:
            transactions.append(
                Transactions(
                    amount=Decimal(str(random.uniform(2500, 3200))),
                    category=enums.TransactionCategoryEnum.savings,
                    description=f"Bi-weekly paycheck - {current_date.strftime('%Y-%m-%d')}",
                    date=current_date,
                    type=enums.TransactionTypeEnum.income,
                    savings_goal_id=None,
                )
            )

        transactions.append(
            Transactions(
                amount=Decimal("1400.00"),
                category=enums.TransactionCategoryEnum.rent,
                description="Monthly rent payment",
                date=current_date.replace(day=1),
                type=enums.TransactionTypeEnum.expense,
                savings_goal_id=None,
            )
        )

        for _ in range(random.randint(2, 4)):
            transactions.append(
                Transactions(
                    amount=Decimal(str(random.uniform(30, 80))),
                    category=enums.TransactionCategoryEnum.food,
                    description=fake.sentence(nb_words=4),
                    date=current_date - timedelta(days=random.randint(0, 5)),
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                )
            )

        if random.random() < 0.3:
            transactions.append(
                Transactions(
                    amount=Decimal(str(random.uniform(20, 60))),
                    category=enums.TransactionCategoryEnum.transport,
                    description=fake.sentence(nb_words=3),
                    date=current_date,
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                )
            )

        if random.random() < 0.2:
            transactions.append(
                Transactions(
                    amount=Decimal(str(random.uniform(15, 80))),
                    category=enums.TransactionCategoryEnum.entertainment,
                    description=fake.sentence(nb_words=3),
                    date=current_date,
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                )
            )

        if current_date.day == 15:
            transactions.extend([
                Transactions(
                    amount=Decimal(str(random.uniform(40, 80))),
                    category=enums.TransactionCategoryEnum.utilities,
                    description="Electric bill",
                    date=current_date,
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                ),
                Transactions(
                    amount=Decimal(str(random.uniform(60, 100))),
                    category=enums.TransactionCategoryEnum.utilities,
                    description="Internet bill",
                    date=current_date,
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                ),
            ])

        if random.random() < 0.4:
            transactions.append(
                Transactions(
                    amount=Decimal(str(random.uniform(10, 20))),
                    category=enums.TransactionCategoryEnum.subscriptions,
                    description=random.choice(["Netflix", "Spotify", "Disney+", "Hulu", "Amazon Prime"]),
                    date=current_date,
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                )
            )

        if random.random() < 0.1:
            transactions.append(
                Transactions(
                    amount=Decimal(str(random.uniform(100, 300))),
                    category=enums.TransactionCategoryEnum.concerts,
                    description=f"Concert: {fake.name()}",
                    date=current_date,
                    type=enums.TransactionTypeEnum.expense,
                    savings_goal_id=None,
                )
            )

        transactions.append(
            Transactions(
                amount=Decimal(str(random.uniform(100, 500))),
                category=enums.TransactionCategoryEnum.savings,
                description="Transfer to savings",
                date=current_date,
                type=enums.TransactionTypeEnum.expense,
                savings_goal_id=1,
            )
        )

        current_date += timedelta(days=14)

    for txn in transactions:
        txn.add_transaction(config.session)

    print(f"Added {len(transactions)} transactions")


def main():
    print("Starting database seed...")
    print("-" * 40)

    seed_savings_goals()
    seed_debts()
    seed_crypto_holdings()
    seed_transactions()

    print("-" * 40)
    print("Database seeding complete!")


if __name__ == "__main__":
    main()
